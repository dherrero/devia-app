import type { SkillRegistryEntry } from '../../../../shared/domain/skill-registry';

/**
 * Renders the per-project skill registry as a deterministic Markdown
 * document. The output is the source of truth the agent reads at
 * session start (via the system-prompt pointer in `runner` wiring) and
 * the file the renderer opens in the SpecViewer dialog.
 *
 * Determinism matters: the writer is called repeatedly (on project
 * switch, on fs.watch tick, on manual refresh) and the use case skips
 * a write when the body matches what is already on disk. Any source of
 * non-determinism here (a timestamp inside the body, a non-stable sort)
 * would defeat that optimisation and cause an endless watcher loop.
 *
 * The "How to use this index" block is a one-shot LLM contract: tells
 * the model to read the matching `SKILL.md` body before acting.
 */
export function renderSkillRegistry(
  entries: ReadonlyArray<SkillRegistryEntry>,
  projectPath: string,
): string {
  const head = [
    '# Skills available in this project',
    '',
    'This file is auto-generated by Devia (`#269`). Do not edit by hand —',
    'changes are overwritten on the next refresh.',
    '',
    '## How to use this index',
    '',
    'For each row, the `Path` column points at the canonical `SKILL.md`',
    'authoring file. **Read the matching `SKILL.md` body BEFORE executing**',
    'tasks that match its description — the body is the source of truth.',
    'Never paraphrase a skill from this index; it lists triggers only.',
    '',
    '## Skills',
    '',
  ].join('\n');

  if (entries.length === 0) {
    return `${head}_No skills detected for this project._\n`;
  }

  const rows = entries.map(
    (e) =>
      `| ${escapeCell(e.name)} | ${escapeCell(e.description)} | ${e.scope} | ${escapeCell(
        relativiseIfInside(e.path, projectPath),
      )} |`,
  );

  return [
    head,
    '| Name | Trigger / description | Scope | Path |',
    '|------|-----------------------|-------|------|',
    ...rows,
    '',
  ].join('\n');
}

/**
 * If the SKILL.md lives inside the project tree, render the path as
 * project-relative so the file stays portable across machines (a user
 * sharing the project keeps the absolute homedir out of the file).
 * Global-scope skills keep their absolute path because they're machine-
 * local anyway.
 */
function relativiseIfInside(absPath: string, projectPath: string): string {
  if (!absPath.startsWith(projectPath)) return absPath;
  const tail = absPath.slice(projectPath.length);
  if (!tail.startsWith('/') && !tail.startsWith('\\')) return absPath;
  return tail.slice(1).replace(/\\/g, '/');
}

function escapeCell(value: string): string {
  // GFM table cells can't contain unescaped pipes or newlines without
  // breaking the row layout. Replacing them keeps the table valid
  // without forcing us to multi-line the description column.
  return value.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}
