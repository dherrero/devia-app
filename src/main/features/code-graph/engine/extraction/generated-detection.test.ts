import { describe, expect, it } from 'vitest';
import { isGeneratedFile } from './generated-detection';

describe('isGeneratedFile', () => {
  it('detects by path', () => {
    expect(isGeneratedFile('api.pb.go', '')).toBe(true);
    expect(isGeneratedFile('lib/a.g.dart', '')).toBe(true);
    expect(isGeneratedFile('lib/a.freezed.dart', '')).toBe(true);
    expect(isGeneratedFile('dist/app.min.js', '')).toBe(true);
  });

  it('detects by banner', () => {
    expect(isGeneratedFile('main.go', '// Code generated by protoc. DO NOT EDIT.')).toBe(true);
    expect(isGeneratedFile('a.ts', '// @generated\nexport {}')).toBe(true);
    expect(isGeneratedFile('a.py', '# GENERATED by tool. DO NOT EDIT')).toBe(true);
  });

  it('detects the bare GENERATED header and the Dart build_runner banner', () => {
    expect(isGeneratedFile('lib/api.dart', '// GENERATED CODE - DO NOT MODIFY BY HAND\npart of api;')).toBe(true);
    expect(isGeneratedFile('a.ts', '// GENERATED\nexport const x = 1;')).toBe(true);
    expect(isGeneratedFile('a.py', '# GENERATED\nx = 1')).toBe(true);
  });

  it('does not treat a comment that merely mentions generation as a banner', () => {
    expect(isGeneratedFile('a.ts', '// GENERATED files live in gen/\nexport {}')).toBe(false);
    expect(isGeneratedFile('a.ts', '// generated\nexport {}')).toBe(false);
  });

  it('rejects hand-written files', () => {
    expect(isGeneratedFile('main.go', 'package main')).toBe(false);
    expect(isGeneratedFile('main.go', 'var s = "Code generated by x. DO NOT EDIT."')).toBe(false);
  });
});
