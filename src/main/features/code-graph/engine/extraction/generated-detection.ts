const PATH_PATTERNS: ReadonlyArray<RegExp> = [
  /\.pb\.go$/,
  /\.pulsar\.go$/,
  /_mocks?\.go$/,
  /^mock_[^/]+\.go$/,
  /\.generated\.[jt]sx?$/,
  /\.gen\.[jt]sx?$/,
  /\.pb\.[jt]s$/,
  /_pb\.[jt]s$/,
  /_grpc_pb\.[jt]s$/,
  /[.-]min\.m?js$/,
  /_pb2(_grpc)?\.pyi?$/,
  /OuterClass\.java$/,
  /Grpc\.java$/,
  /\.g\.dart$/,
  /\.freezed\.dart$/,
  /\.pb\.dart$/,
  /\.pbgrpc\.dart$/,
  /\.chopper\.dart$/,
];

const HEADER_SCAN_CHARS = 8192;
const HEADER_SCAN_LINES = 60;
const GENERATED_STEM = /generat/i;
const COMMENT_LEADER =
  /^\s*(?:\/\/|\/\*+|\*+\/?|#+|--+|<!--|%+|;+|'|!|\(\*|\{-|"""|'''|=begin|<#)/;

const BANNER_PATTERNS: ReadonlyArray<RegExp> = [
  /\bcode generated\b.{0,200}?\bdo not edit\b/i,
  /\b(?:automatically |auto[- ]?)?generated (?:by|from|with)\b.{0,200}?\bdo not (?:edit|modify|change)\b/i,
  /(?:^|[^\p{L}\p{N}_@])@generated\b/u,
  /<auto-?generated\s*\/?>/i,
  /\b(?:automatically generated|auto[- ]?generated|autogenerated) by\b/i,
  /\bthis (?:file|class|code|module) (?:is|was) (?:auto[- ]?)?generated\b/i,
  /\bdo not (?:edit|modify)\b.{0,120}?\b(?:auto[- ]?generated|generated file|generated code)\b/i,
  // Dart build_runner / source_gen: `// GENERATED CODE - DO NOT MODIFY BY HAND`.
  /\bgenerated code\b.{0,40}?\bdo not (?:edit|modify|change)\b/i,
  // A bare upper-case `// GENERATED` (or `# GENERATED`) header line.
  /^\s*(?:\/\/+|#+|\/\*+|--+)\s*GENERATED\s*(?:\*+\/)?\s*$/,
];

const BLOCK_DELIMS: ReadonlyArray<{ open: string; close: string }> = [
  { open: '/*', close: '*/' },
  { open: '<!--', close: '-->' },
  { open: '"""', close: '"""' },
  { open: "'''", close: "'''" },
];

function hasGeneratedBanner(head: string): boolean {
  if (!head) return false;
  const scan = head.length > HEADER_SCAN_CHARS ? head.slice(0, HEADER_SCAN_CHARS) : head;
  if (!GENERATED_STEM.test(scan)) return false;
  const lines = scan.split('\n');
  const limit = Math.min(lines.length, HEADER_SCAN_LINES);
  let openBlock: { open: string; close: string } | null = null;
  for (let i = 0; i < limit; i++) {
    const line = lines[i]!;
    if (openBlock !== null || COMMENT_LEADER.test(line)) {
      if (BANNER_PATTERNS.some((p) => p.test(line))) return true;
    }
    if (openBlock) {
      if (line.includes(openBlock.close)) openBlock = null;
      continue;
    }
    for (const delim of BLOCK_DELIMS) {
      const at = line.indexOf(delim.open);
      if (at < 0) continue;
      if (line.indexOf(delim.close, at + delim.open.length) < 0) openBlock = delim;
      break;
    }
  }
  return false;
}

export function isGeneratedFile(relPath: string, head: string): boolean {
  const normalised = relPath.replace(/\\/g, '/');
  return PATH_PATTERNS.some((p) => p.test(normalised)) || hasGeneratedBanner(head);
}
