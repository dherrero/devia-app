/**
 * Per-run delivery of Devia's bundled MCP servers to pi — the pi equivalent of
 * Claude's `--mcp-config <file>`.
 *
 * Why not `.pi/mcp.json` like the other non-Claude agents: pi reads the project
 * file ONLY when the project is trusted (`~/.pi/agent/trust.json`), and RPC mode
 * cannot ask. A session worktree (`<deviaDir>/worktrees/...`) is never trusted,
 * so the servers silently vanished there; `--approve` would fix that but also
 * load every extension the repo ships under `.pi/`. An extension passed with
 * `-e` loads regardless of trust and can call `pi.registerMcpServer()` for the
 * current session only — nothing is persisted, nothing touches the repo.
 *
 * Verified with pi 1.3.0: registered servers connect at session start and,
 * with `exposure: 'direct'`, their tools are declared to the model like
 * built-ins (named `mcp__<server>__<tool>`, server sanitised to `[A-Za-z0-9_]`).
 */
import * as crypto from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';

import type { McpServerConfig } from '../../../../shared/domain/mcp';
import { DEVIA_MANAGED_KEY } from '../../mcp/infrastructure/marker-merge';
import { composeServerEnv, type TempMcpConfig } from '../../mcp/infrastructure/temp-config-writer';

/** Ids Devia used to write into `.pi/mcp.json` before the extension delivery. */
const RETIRED_PROJECT_IDS = ['devia-memory', 'devia-kanban', 'devia-ui', 'devia-ask'];

interface PiServerEntry {
  command: string;
  args: string[];
  env?: Record<string, string>;
  exposure: string;
  description?: string;
  timeout?: number;
}

/** Build the extension module source. Exported for tests. */
export function buildPiMcpExtensionSource(
  servers: readonly McpServerConfig[],
  parentEnv: NodeJS.ProcessEnv,
): string {
  const entries: Record<string, PiServerEntry> = {};
  for (const s of servers) {
    const env = composeServerEnv(s, parentEnv);
    entries[s.id] = {
      command: s.command,
      args: [...s.args],
      ...(Object.keys(env).length > 0 && { env }),
      // Devia's tools must be callable without codemode / tool_search.
      exposure: s.exposure ?? 'direct',
      ...(s.description !== undefined && { description: s.description }),
      // Blocking devia-ui tools wait for the user; pi's default request
      // timeout (60 s) would cut them off long before Devia's own 5 min.
      ...(s.id === 'devia-ui' && { timeout: 6 * 60 }),
    };
  }
  return [
    '// Generated by Devia for one pi run. Safe to delete.',
    `const SERVERS = ${JSON.stringify(entries, null, 2)};`,
    'export default function deviaMcp(pi) {',
    '  for (const [name, config] of Object.entries(SERVERS)) pi.registerMcpServer(name, config);',
    '}',
    '',
  ].join('\n');
}

/**
 * Write the extension under `<deviaDir>/tmp/` and return its path plus a
 * cleanup. The runner appends `['-e', path]` to pi's argv.
 */
export function writePiMcpExtension(
  servers: readonly McpServerConfig[],
  deviaDir: string,
  parentEnv: NodeJS.ProcessEnv,
): TempMcpConfig | null {
  if (servers.length === 0) return null;
  const tmpDir = path.join(deviaDir, 'tmp');
  const filePath = path.join(tmpDir, `pi-mcp-${crypto.randomUUID()}.mjs`);
  try {
    fs.mkdirSync(tmpDir, { recursive: true });
    fs.writeFileSync(filePath, buildPiMcpExtensionSource(servers, parentEnv), { encoding: 'utf8', mode: 0o600 });
  } catch (err) {
    console.warn('[mcp] failed to write the pi MCP extension:', err instanceof Error ? err.message : String(err));
    return null;
  }
  return {
    path: filePath,
    cleanup(): void {
      try { fs.unlinkSync(filePath); } catch { /* best-effort */ }
    },
  };
}

/**
 * Remove the Devia-managed entries earlier versions wrote into
 * `<cwd>/.pi/mcp.json`. They must go: a file entry OVERRIDES a registered
 * server with the same name, so a stale `devia-ui` (pointing at a dead
 * per-run `--ui-dir`) would shadow the live one. Hand-added entries are kept;
 * a file left with nothing in it is deleted. Best-effort, never throws.
 */
export function retirePiProjectMcp(cwd: string): void {
  const file = path.join(cwd, '.pi', 'mcp.json');
  let root: Record<string, unknown>;
  try {
    const parsed: unknown = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return;
    root = parsed as Record<string, unknown>;
  } catch {
    return; // missing or malformed — nothing of ours to clean
  }
  const servers = root['mcpServers'];
  if (!servers || typeof servers !== 'object' || Array.isArray(servers)) return;
  const kept: Record<string, unknown> = {};
  let removed = false;
  for (const [id, entry] of Object.entries(servers as Record<string, unknown>)) {
    const marker = entry && typeof entry === 'object' ? (entry as Record<string, unknown>)[DEVIA_MANAGED_KEY] : undefined;
    if (RETIRED_PROJECT_IDS.includes(id) && (marker === id || marker === 'devia')) {
      removed = true;
      continue;
    }
    kept[id] = entry;
  }
  if (!removed) return;
  try {
    const next: Record<string, unknown> = { ...root };
    if (Object.keys(kept).length > 0) next['mcpServers'] = kept;
    else delete next['mcpServers'];
    if (Object.keys(next).length === 0) {
      fs.unlinkSync(file);
    } else {
      fs.writeFileSync(file, JSON.stringify(next, null, 2) + '\n', 'utf8');
    }
  } catch (err) {
    console.warn('[mcp] could not clean Devia entries from .pi/mcp.json:', err instanceof Error ? err.message : String(err));
  }
}
